    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        
        String dname= jTextField1.getText();
        String amount=jTextField2.getText();
        String accountno=jTextField4.getText();
        String mpdamount=jTextField5.getText();
        
        double updateamount=damount-Double.parseDouble(mpdamount);
        
        String cgrant= new DonationInformationExtractor().getCharityTransactions(cname);
        double totalamount=0.0;
        
        if(cgrant.isEmpty())
        {
          totalamount=Double.parseDouble(amount)+Double.parseDouble(mpdamount); 
        }
        else
        {
          totalamount=Double.parseDouble(cgrant)+Double.parseDouble(amount)+Double.parseDouble(mpdamount);  
        }
        
        
               
       
          if(amount.equals("0"))
        {
            JOptionPane.showMessageDialog(null, "Donation amount should not be zero");
        }
         else if(accountno.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Account Number");
        }
         
        
          else
        {
  
            if(cgrant.isEmpty())
            {
               DonationAmountInserter mi=new DonationAmountInserter();
            MatchingPartnerInformationUpdate mp=new MatchingPartnerInformationUpdate();
            
            if(mi.insertMatchingPartnersDonationinfo(dname, amount,cname, accountno, mpdamount)&& mp.updateMatchingPartnerDonationamount(donorid, pname, Double.toString(updateamount))&&mi.insertCharityGrantinfo(cname, Double.toString(totalamount)))
                JOptionPane.showMessageDialog(null, "Donation Amount Submitted Successfully");
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error"); 
            }
            
            else
            {
              DonationAmountInserter mi=new DonationAmountInserter();
             MatchingPartnerInformationUpdate mp=new MatchingPartnerInformationUpdate();
             DonationAmountUpdate du=new DonationAmountUpdate();
            
            if(mi.insertMatchingPartnersDonationinfo(dname, amount,cname, accountno, mpdamount)&& mp.updateMatchingPartnerDonationamount(donorid, pname, Double.toString(updateamount))&&du.updateDonationAmount(cname, Double.toString(totalamount)))
                JOptionPane.showMessageDialog(null, "Donation Amount Submitted Successfully");
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error");   
            }
            
        }

          
    }//GEN-LAST:event_jButton3ActionPerformed

