    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        
          String pname=(String) jComboBox1.getSelectedItem();
          String damount=jTextField1.getText();
          
            if(pname.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Select Matching Partner Poolname");
        }
         else if(damount.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Donation Amount");
        }
         else if(!damount.matches("[0-9]+"))
        {
            JOptionPane.showMessageDialog(null, "Donation amount should be in numbers only");
        }
         
        
          else
        {
           ArrayList charitylistinfo=new MatchingPartnersInformationExtractor().getCharityDonationInfo();
           
           double damt=0.0;
           
            for (int i = 0; i <charitylistinfo.size(); i++)
        {
            ArrayList row=(ArrayList) charitylistinfo.get(i);
            
            String donorid=(String) row.get(0);
            String pname1=(String) row.get(1);
            
            if(donorid.equals(LoginFrame.userid) && pname1.equals(pname))
            {
                damt=Double.parseDouble((String) row.get(3));
            }
            
            
        }
            
            double newamount=Double.parseDouble(damount)+damt;
            
             MatchingPartnerInformationUpdate mp=new MatchingPartnerInformationUpdate();
            if(mp.updateMatchingPartnerDonationamount(LoginFrame.userid, pname, Double.toString(newamount)))
                JOptionPane.showMessageDialog(null, "Donation Amount Submitted Successfully");
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error");
        }
         
    }//GEN-LAST:event_jButton2ActionPerformed

