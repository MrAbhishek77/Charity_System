    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        // TODO add your handling code here:

        String type=(String) jComboBox1.getSelectedItem();

        System.out.println("type: "+type);
        type=type.trim();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        if(type.equals("Select"))
        {
            JOptionPane.showMessageDialog(null, "Please Select Transactions Type");
        }

        else
        {

            if(type.equals("View Pool Transactions"))
            {

                model.setRowCount(0);
                
                String userid=LoginFrame.userid;
                
                System.out.println("userid: "+userid);
                ArrayList charitiesname=new MatchingPartnersInformationExtractor().getCharitiesNames(userid);
               
                ArrayList chnames=new ArrayList();
                for (int i = 0; i <charitiesname.size(); i++) 
                {
                    String ch1=(String) charitiesname.get(i);
                    String ch[]=ch1.split(",");
                    
                    for (int j = 0; j <ch.length; j++) 
                    {
                        chnames.add(ch[j]);
                    }
                }
                
                ArrayList alltraninfo=new ArrayList();
                
                for (int i = 0; i <chnames.size(); i++) 
                {
                  ArrayList transactinfo=new CharityTransactionInformationExtractor().getCharityTransactionInfo((String) chnames.get(i)); 
                  if(transactinfo.size()!=0)
                  alltraninfo.add(transactinfo);
                }

                if(alltraninfo.size()==0)
                {
                    JOptionPane.showMessageDialog(null, "No Transactions Record of Pooled Charities");
                
                }
                else
                {
                    DefaultTableCellRenderer rendar = new DefaultTableCellRenderer();
                rendar.setHorizontalAlignment((int) CENTER_ALIGNMENT);

                jTable1.setRowHeight(30);

                int x = jTable1.getColumnCount();
                for (int i = 0; i < x; i++)
                {
                    jTable1.getColumnModel().getColumn(i).setCellRenderer(rendar);
                }

                Object rowData[] = new Object[6];

                for(int i=0;i<alltraninfo.size();i++)
                {

                    ArrayList chtransac=(ArrayList) alltraninfo.get(i);
                    
                    for (int j = 0; j <chtransac.size(); j++) 
                    {
                        ArrayList temp=(ArrayList) chtransac.get(j);
                        
                        for (int k = 0; k <temp.size(); k++) 
                        {
                            String str=(String) temp.get(k);
                        System.out.println(str);
                        rowData[k]=str;
                        }
                       model.addRow(rowData);
                    }
                      
                                    }
                    
                }
                
            }

            else if(type.equals("View Individual Transactions"))
            {
                model.setRowCount(0);
                
                ArrayList chnames=new DonationInformationExtractor().getDonorCharityTransactions(LoginFrame.userid);
                
                HashSet hs=new HashSet();      
                hs.addAll(chnames);
                chnames.clear();
                chnames.addAll(hs);

                ArrayList alltraninfo=new ArrayList();
                
                for (int i = 0; i <chnames.size(); i++) 
                {
                  ArrayList transactinfo=new CharityTransactionInformationExtractor().getCharityTransactionInfo((String) chnames.get(i)); 
                  if(transactinfo.size()!=0)
                  alltraninfo.add(transactinfo);
                }

                
               // System.out.println("transactions info: "+alltraninfo);
               
               if(alltraninfo.size()==0)
                {
                    JOptionPane.showMessageDialog(null, "No Transactions Record of Donated Charities");
                
                }
               else
               {
                    DefaultTableCellRenderer rendar = new DefaultTableCellRenderer();
                rendar.setHorizontalAlignment((int) CENTER_ALIGNMENT);

                jTable1.setRowHeight(30);

                int x = jTable1.getColumnCount();
                for (int i = 0; i < x; i++)
                {
                    jTable1.getColumnModel().getColumn(i).setCellRenderer(rendar);
                }

                Object rowData[] = new Object[6];

                for(int i=0;i<alltraninfo.size();i++)
                {

                    ArrayList chtransac=(ArrayList) alltraninfo.get(i);
                    
                    for (int j = 0; j <chtransac.size(); j++) 
                    {
                        ArrayList temp=(ArrayList) chtransac.get(j);
                        
                        for (int k = 0; k <temp.size(); k++) 
                        {
                            String str=(String) temp.get(k);
                        System.out.println(str);
                        rowData[k]=str;
                        }
                        model.addRow(rowData);
                    }
                     
                                    }
                   
               }
               
            }

            
            else
            {
                JOptionPane.showMessageDialog(null, "Oops There is Some Error");
            }
        }
    }//GEN-LAST:event_jComboBox1ActionPerformed

