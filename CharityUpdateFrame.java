    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        
        String cname=jTextField1.getText();
        cname=cname.trim();
        String crno=jTextField2.getText();
        crno=crno.trim();
        String add=jTextArea1.getText();
        add=add.trim();
        String contact=jTextField4.getText();
        contact=contact.trim();
        String email=jTextField5.getText();
        email=email.trim();
        String descript=jTextArea2.getText();
        descript=descript.trim();
        String category=(String) jComboBox1.getSelectedItem();
        category=category.trim();
        String nobranch=jTextField7.getText();
        nobranch=nobranch.trim();
        String uname=jTextField8.getText();
        uname=uname.trim();
        String pass=jPasswordField1.getText();
        String cpass=jPasswordField2.getText();
       
          if(cname.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Name");
        }
        else if(crno.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Registration Number");
        }
        else if(isInteger(crno)==false)
        {
            JOptionPane.showMessageDialog(null, "Charity Registration Number shoukd be in Integer Only");
        }
          else if(add.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Address");
        }
          else if (contact.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Contact Number");
        } else if (contact.length() != 10) {
            JOptionPane.showMessageDialog(null, "Mobile Number should be of 10 Digits");
        }
         else if (!email.contains("@")) {
            JOptionPane.showMessageDialog(null, "Email ID does not contains '@' Please try Again");

        } else if (!email.contains(".")) {
            JOptionPane.showMessageDialog(null, "Email ID does not contains '.' Please try Again");

        }
          else if(descript.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Description");
        }
           else if(category.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Select Charity Category");
        }
          else if(nobranch.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Branches Number");
        }
          else if(isInteger(nobranch)==false)
        {
            JOptionPane.showMessageDialog(null, "Charity Branches Number shoukd be in Integer Only");
        }
        
        
          else if (pass.isEmpty() )
        {
            JOptionPane.showMessageDialog(null, "Please Enter Password");
        }
        else if (cpass.isEmpty() )
        {
            JOptionPane.showMessageDialog(null, "Please Enter Confirm Password");
        }
        else if (!pass.equals(cpass))
        {
            JOptionPane.showMessageDialog(null, "Both Password Are Not Same");
        }
          else
        {
            
            System.out.println("add: "+add);
            UpdatedCharitynformation cdb=new UpdatedCharitynformation();
            if(cdb.updateCharityinfo(uname, crno, add, contact, email, descript, category, nobranch, uname, barr1,fis1,pass))
                JOptionPane.showMessageDialog(null, "Charity Information Updated Successfully");
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error");
        }

          
    }//GEN-LAST:event_jButton3ActionPerformed

