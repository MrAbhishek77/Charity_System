    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String chname=jTextField5.getText();
        String description=jTextField1.getText();
        String amount=jTextField2.getText();
        String paidto=jTextField3.getText();
        
        chname=chname.trim();
        description=description.trim();
        amount=amount.trim();
        paidto=paidto.trim();
        
        if(chname.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Name");
        }
        else if(description.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Charity Description");
        }
         else if(amount.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Amount");
        }
        else if(isDouble(amount)==false)
        {
            JOptionPane.showMessageDialog(null, "Amount should be in numbers only");
        }
        else if(paidto.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Beneficiary Name");
        }
        else
        {
            String dtime=new CurrentDate().getDateTime();
            
            ArrayList chspendinfo=new CharityTransactionInformationExtractor().getCharityTransactionInfo(chname);
            
            double udatedgrant=Double.parseDouble(cgrantamount)-Double.parseDouble(amount);
            udatedgrant=Double.parseDouble(new DecimalFormat("##.##").format(udatedgrant));
            
            jLabel6.setText("Total Balance is: "+Double.toString(udatedgrant));
            
            CharityGrantAmountUpdate cu=new CharityGrantAmountUpdate();
            CharityTransactionInformationInserter cdb=new CharityTransactionInformationInserter();
            
            if(chspendinfo.size()==0)
            {
            String spentinfo=chname+description+amount+paidto+dtime;
            spentinfo=spentinfo.trim();
            String blockkey= new KeyGen().getKey(spentinfo);
            
            
            if(cdb.insertCharityTransactioninfo(chname, description, amount, paidto, dtime, blockkey)&&cu.updateDonationAmount(chname, Double.toString(udatedgrant)))
            {
               JOptionPane.showMessageDialog(null, "Charity Transaction Information Submitted Successfully");
               cgrantamount=Double.toString(udatedgrant);  
                jTextField1.setText("");  
                jTextField2.setText("");  
                jTextField3.setText(""); 
            } 
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error"); 
            }

            else
            {
                ArrayList lasttransarow=(ArrayList) chspendinfo.get(chspendinfo.size()-1);
                String lastheadkey=(String) lasttransarow.get(lasttransarow.size()-1);
                
                System.out.println("lastheadkey: "+lastheadkey);
                
                 String spentinfo=chname+description+amount+paidto+dtime;
                 spentinfo=spentinfo.trim();
                 
                 System.out.println("spentinfo: "+spentinfo);
                 spentinfo=spentinfo+lastheadkey;
                 String blockkey= new KeyGen().getKey(spentinfo);
               
            if(cdb.insertCharityTransactioninfo(chname, description, amount, paidto, dtime, blockkey)&&cu.updateDonationAmount(chname, Double.toString(udatedgrant)))
                {
               JOptionPane.showMessageDialog(null, "Charity Transaction Information Submitted Successfully");
                cgrantamount=Double.toString(udatedgrant); 
                jTextField1.setText("");  
                jTextField2.setText("");  
                jTextField3.setText(""); 
               }
             else
             JOptionPane.showMessageDialog(null, "Oops There is Some Error"); 
            }
 
        }
    }//GEN-LAST:event_jButton3ActionPerformed

