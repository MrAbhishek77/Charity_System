    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
          
      
        userid=jTextField1.getText();
        String pass=jPasswordField1.getText();
        String user="";
        
        if(jRadioButton1.isSelected())
        {
            user= jRadioButton1.getText();
        }
        else  if(jRadioButton2.isSelected())
        {
            user= jRadioButton2.getText();
        }
        
        if(userid.isEmpty())
        {
            JOptionPane.showMessageDialog(null,"Username Cannot be Empty");

        }
        else if(user.isEmpty())
        {
            JOptionPane.showMessageDialog(null,"Select the User as a Charity or Donor");
        }

        else if(pass.isEmpty())
        {
            JOptionPane.showMessageDialog(null,"Password Cannot be Empty");
        }

        else if(user.equals("Charity"))
        {
            LoginChecker lc=new LoginChecker();

            if(lc.checkCharityLogin(userid,pass))
            {
                this.dispose();
                Dimension d=Toolkit.getDefaultToolkit().getScreenSize();
                CharityOperationFrame af=new CharityOperationFrame();
                af.setVisible(true);
                af.setSize(d);
              
           }
            else
            {
                
                    JOptionPane.showMessageDialog(null,"Please Enter Correct User ID and Password");   
            }
          
        }
        else if(user.equals("Donor"))
        {
            LoginChecker lc=new LoginChecker();

            if(lc.checkDonorLogin(userid,pass))
            {
                this.dispose();
                Dimension d=Toolkit.getDefaultToolkit().getScreenSize();
                DonorOperationFrame af=new DonorOperationFrame();
                af.setVisible(true);
                af.setSize(d);
              
           }
            else
            {
                
                    JOptionPane.showMessageDialog(null,"Please Enter Correct User ID and Password");   
            }
          
        }
       
    }//GEN-LAST:event_jButton1ActionPerformed

